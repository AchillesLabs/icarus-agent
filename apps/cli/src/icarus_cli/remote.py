"""Remote HTTP and Server-Sent Events (SSE) API client for Icarus Agent."""

import json
from collections.abc import AsyncGenerator
from dataclasses import dataclass, field
from typing import Any

import httpx
from icarus_contracts.context import CompactionResult
from icarus_contracts.session import (
    MessageCreateRequest,
    MessageDTO,
    MessageResponse,
    MessageRole,
    RunCancelResponse,
    RunCreateRequest,
    RunResponse,
    SessionCreateRequest,
    SessionListResponse,
    SessionResponse,
    SSEEventPayload,
    SSEEventType,
)
from icarus_contracts.tools import ToolCall, ToolResult

from icarus_cli.observer import RichAgentObserver


@dataclass
class RemoteRunResult:
    """Execution telemetry and final response generated by a remote agent run."""

    content: str
    session_id: str
    run_id: str | None = None
    status: str = "succeeded"
    budget_counters: dict[str, Any] = field(default_factory=dict)
    finish_reason: str = "stop"


class RemoteAgentClient:
    """HTTP and SSE streaming client connecting to a remote Icarus API server."""

    def __init__(
        self,
        base_url: str,
        api_key: str | None = None,
        timeout: float = 60.0,
        transport: httpx.AsyncBaseTransport | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.api_key = api_key
        self.timeout = timeout
        self.transport = transport
        self._client: httpx.AsyncClient | None = None

    def _get_headers(self) -> dict[str, str]:
        headers = {"Accept": "application/json"}
        if self.api_key:
            headers["Authorization"] = f"Bearer {self.api_key}"
        return headers

    async def get_client(self) -> httpx.AsyncClient:
        """Return an active httpx.AsyncClient instance."""
        if self._client is None or self._client.is_closed:
            self._client = httpx.AsyncClient(
                base_url=self.base_url,
                headers=self._get_headers(),
                timeout=self.timeout,
                transport=self.transport,
            )
        return self._client

    async def close(self) -> None:
        """Close the underlying HTTP client session."""
        if self._client is not None and not self._client.is_closed:
            await self._client.aclose()
            self._client = None

    async def __aenter__(self) -> "RemoteAgentClient":
        await self.get_client()
        return self

    async def __aexit__(self, exc_type: Any, exc_val: Any, exc_tb: Any) -> None:
        await self.close()

    async def check_health(self) -> dict[str, Any]:
        """Query /health endpoint to check server status."""
        client = await self.get_client()
        resp = await client.get("/health")
        resp.raise_for_status()
        return resp.json()

    async def list_sessions(self, limit: int = 50, offset: int = 0) -> SessionListResponse:
        """Retrieve paginated session summaries from GET /v1/sessions."""
        client = await self.get_client()
        resp = await client.get("/v1/sessions", params={"limit": limit, "offset": offset})
        resp.raise_for_status()
        return SessionListResponse.model_validate(resp.json())

    async def get_session(self, session_id: str) -> SessionResponse:
        """Retrieve a specific session by ID from GET /v1/sessions/{id}."""
        client = await self.get_client()
        resp = await client.get(f"/v1/sessions/{session_id}")
        resp.raise_for_status()
        return SessionResponse.model_validate(resp.json())

    async def create_session(
        self,
        title: str = "New Session",
        mode: str = "chat",
    ) -> SessionResponse:
        """Create a new conversation session via POST /v1/sessions."""
        client = await self.get_client()
        req = SessionCreateRequest(title=title, mode=mode)
        resp = await client.post("/v1/sessions", json=req.model_dump())
        resp.raise_for_status()
        return SessionResponse.model_validate(resp.json())

    async def list_messages(self, session_id: str) -> list[MessageDTO]:
        """Fetch chronological messages for a session via GET /v1/sessions/{id}/messages."""
        client = await self.get_client()
        resp = await client.get(f"/v1/sessions/{session_id}/messages")
        resp.raise_for_status()
        return [MessageDTO.model_validate(m) for m in resp.json()]

    async def post_message(
        self,
        session_id: str,
        role: MessageRole | str,
        content: str,
    ) -> MessageResponse:
        """Append a message to a session thread via POST /v1/sessions/{id}/messages."""
        client = await self.get_client()
        req = MessageCreateRequest(role=role, content=content)
        resp = await client.post(f"/v1/sessions/{session_id}/messages", json=req.model_dump())
        resp.raise_for_status()
        return MessageResponse.model_validate(resp.json())

    async def cancel_run(self, run_id: str) -> RunCancelResponse:
        """Cancel an in-flight agent run via POST /v1/runs/{id}/cancel."""
        client = await self.get_client()
        resp = await client.post(f"/v1/runs/{run_id}/cancel")
        resp.raise_for_status()
        return RunCancelResponse.model_validate(resp.json())

    async def execute_run(
        self,
        session_id: str,
        prompt: str,
        model: str | None = None,
        provider: str | None = None,
        temperature: float | None = None,
        max_turns: int | None = None,
        max_total_tokens: int | None = None,
        auto_compact: bool = True,
        auto_approve: bool = True,
    ) -> RunResponse:
        """Execute a synchronous one-shot run via POST /v1/sessions/{id}/runs."""
        client = await self.get_client()
        url = f"/v1/sessions/{session_id}/runs"
        payload = RunCreateRequest(
            prompt=prompt,
            model=model,
            provider=provider,
            temperature=temperature,
            max_turns=max_turns,
            max_total_tokens=max_total_tokens,
            auto_compact=auto_compact,
            auto_approve=auto_approve,
        ).model_dump(exclude_none=True)
        resp = await client.post(url, json=payload, headers=self._get_headers())
        resp.raise_for_status()
        return RunResponse.model_validate(resp.json())

    async def stream_run(
        self,
        session_id: str,
        prompt: str,
        model: str | None = None,
        provider: str | None = None,
        temperature: float | None = None,
        max_turns: int | None = None,
        max_total_tokens: int | None = None,
        auto_compact: bool = True,
        auto_approve: bool = True,
    ) -> AsyncGenerator[SSEEventPayload, None]:
        """Stream an agent run from POST /v1/sessions/{id}/runs/stream emitting typed SSE events."""
        client = await self.get_client()
        url = f"/v1/sessions/{session_id}/runs/stream"
        payload = RunCreateRequest(
            prompt=prompt,
            model=model,
            provider=provider,
            temperature=temperature,
            max_turns=max_turns,
            max_total_tokens=max_total_tokens,
            auto_compact=auto_compact,
            auto_approve=auto_approve,
        ).model_dump(exclude_none=True)

        headers = self._get_headers()
        headers["Accept"] = "text/event-stream"

        async with client.stream("POST", url, json=payload, headers=headers) as response:
            response.raise_for_status()
            current_event: str | None = None
            current_data: list[str] = []

            async for line in response.aiter_lines():
                line = line.strip()
                if not line:
                    if current_data or current_event:
                        data_str = "\n".join(current_data)
                        parsed_data: dict[str, Any] = {}
                        if data_str:
                            try:
                                parsed_data = json.loads(data_str)
                            except json.JSONDecodeError:
                                parsed_data = {"raw": data_str}

                        yield SSEEventPayload(
                            event=current_event or "message",
                            data=parsed_data,
                        )
                        current_event = None
                        current_data = []
                    continue

                if line.startswith("event:"):
                    current_event = line[len("event:") :].strip()
                elif line.startswith("data:"):
                    current_data.append(line[len("data:") :].strip())

            # Yield any trailing event
            if current_data or current_event:
                data_str = "\n".join(current_data)
                parsed_data = {}
                if data_str:
                    try:
                        parsed_data = json.loads(data_str)
                    except json.JSONDecodeError:
                        parsed_data = {"raw": data_str}
                yield SSEEventPayload(
                    event=current_event or "message",
                    data=parsed_data,
                )

    async def execute_remote_run(
        self,
        prompt: str,
        session_id: str | None = None,
        model: str | None = None,
        provider: str | None = None,
        temperature: float | None = None,
        max_turns: int | None = None,
        max_total_tokens: int | None = None,
        auto_compact: bool = True,
        auto_approve: bool = True,
        observer: RichAgentObserver | None = None,
    ) -> RemoteRunResult:
        """Execute a remote agent run and feed real-time SSE events to the RichAgentObserver."""
        effective_session_id = session_id
        if not effective_session_id:
            created_session = await self.create_session(title="Remote Session", mode="chat")
            effective_session_id = created_session.id

        content_parts: list[str] = []
        run_id: str | None = None
        finish_reason = "stop"
        status = "succeeded"
        budget_counters: dict[str, Any] = {}

        async for event in self.stream_run(
            session_id=effective_session_id,
            prompt=prompt,
            model=model,
            provider=provider,
            temperature=temperature,
            max_turns=max_turns,
            max_total_tokens=max_total_tokens,
            auto_compact=auto_compact,
            auto_approve=auto_approve,
        ):
            event_type = event.event.value if hasattr(event.event, "value") else str(event.event)
            data = event.data or {}

            if "run_id" in data and not run_id:
                run_id = str(data["run_id"])

            if event_type == SSEEventType.TURN_START:
                if observer:
                    turn = int(data.get("turn", 1))
                    observer.on_turn_start(turn=turn)

            elif event_type == SSEEventType.TOKEN:
                delta = str(data.get("delta", ""))
                content_parts.append(delta)
                if observer:
                    observer.on_token(delta)

            elif event_type == SSEEventType.TOOL_START:
                if observer:
                    tc = ToolCall(
                        id=data.get("tool_call_id") or "call",
                        name=data.get("tool_name", "tool"),
                        arguments=data.get("arguments", {}),
                    )
                    observer.on_tool_start(tc)

            elif event_type == SSEEventType.TOOL_END:
                if observer:
                    tr = ToolResult(
                        call_id=data.get("tool_call_id") or "call",
                        name=data.get("tool_name", "tool"),
                        output=data.get("output", ""),
                        error=data.get("error"),
                    )
                    observer.on_tool_end(tr)

            elif event_type == SSEEventType.COMPACTION:
                if observer:
                    cr = CompactionResult(
                        original_message_count=data.get("original_count", 0),
                        compacted_message_count=data.get("compacted_count", 0),
                        tokens_saved=data.get("tokens_saved", 0),
                        summary_preview=data.get("summary", ""),
                    )
                    observer.on_compaction(cr)

            elif event_type == SSEEventType.RUN_COMPLETED:
                status = "succeeded"
                finish_reason = "stop"
                if "budget_counters" in data:
                    budget_counters = data["budget_counters"]
                if "result" in data and not content_parts:
                    content_parts.append(str(data["result"]))

            elif event_type == SSEEventType.RUN_CANCELLED:
                status = "cancelled"
                finish_reason = "cancelled"
                if "budget_counters" in data:
                    budget_counters = data["budget_counters"]

            elif event_type == SSEEventType.RUN_FAILED:
                status = "failed"
                finish_reason = "error"
                err_msg = data.get("error", "Remote run failed")
                if not content_parts:
                    content_parts.append(f"\n[Remote Execution Failed: {err_msg}]")

        return RemoteRunResult(
            content="".join(content_parts),
            session_id=effective_session_id,
            run_id=run_id,
            status=status,
            budget_counters=budget_counters,
            finish_reason=finish_reason,
        )
